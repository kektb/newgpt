create extension if not exists pgcrypto;

-- 1. 문항 관리: 대시보드의 Table Editor에서 문항을 바로 수정할 수 있습니다.
create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  order_num integer not null unique,
  title text not null,
  option_a text not null,
  option_b text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint questions_title_length check (char_length(title) between 1 and 2000),
  constraint questions_option_a_length check (char_length(option_a) between 1 and 1000),
  constraint questions_option_b_length check (char_length(option_b) between 1 and 1000)
);

-- 2. 익명 응답 저장
create table if not exists public.responses (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  gender text not null check (gender in ('여성', '남성', '기타', '응답하지 않음')),
  age_group text not null check (age_group in ('10대 이하', '20대', '30대', '40대', '50대', '60대 이상')),
  answers jsonb not null,
  constraint responses_answers_array check (jsonb_typeof(answers) = 'array'),
  constraint responses_three_answers check (jsonb_array_length(answers) = 3)
);

create index if not exists responses_created_at_idx on public.responses (created_at desc);
create index if not exists responses_gender_age_idx on public.responses (gender, age_group);

-- 3. RLS 활성화
alter table public.questions enable row level security;
alter table public.responses enable row level security;

-- 공개 사용자는 활성 문항만 읽을 수 있습니다.
drop policy if exists "Anyone can read active questions" on public.questions;
create policy "Anyone can read active questions"
on public.questions for select
to anon, authenticated
using (is_active = true);

-- 공개 사용자는 응답을 추가할 수 있지만 원본 응답을 직접 읽거나 수정할 수 없습니다.
drop policy if exists "Anyone can submit anonymous responses" on public.responses;
create policy "Anyone can submit anonymous responses"
on public.responses for insert
to anon, authenticated
with check (
  jsonb_typeof(answers) = 'array'
  and jsonb_array_length(answers) = 3
  and char_length(gender) <= 20
  and char_length(age_group) <= 20
);

grant select on public.questions to anon, authenticated;
grant insert on public.responses to anon, authenticated;
revoke all on public.responses from anon, authenticated;

-- 위 revoke 이후 INSERT 권한을 다시 부여합니다.
grant insert on public.responses to anon, authenticated;

-- 4. 통계 전용 RPC
-- 응답 원본 테이블을 공개하지 않고, 집계 결과와 작성 의견만 반환합니다.
create or replace function public.get_public_stats(
  p_gender text default null,
  p_age_group text default null
)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  with filtered as (
    select r.*
    from public.responses r
    where (p_gender is null or r.gender = p_gender)
      and (p_age_group is null or r.age_group = p_age_group)
  ),
  question_stats as (
    select
      q.id,
      q.order_num,
      q.title,
      coalesce(count(*) filter (where a.answer ->> 'choice' = 'A'), 0)::int as a_count,
      coalesce(count(*) filter (where a.answer ->> 'choice' = 'B'), 0)::int as b_count,
      coalesce(count(a.answer), 0)::int as total,
      coalesce((
        select jsonb_agg(opinion order by created_at desc)
        from (
          select jsonb_build_object(
            'choice', answer_item ->> 'choice',
            'reason', answer_item ->> 'reason'
          ) as opinion, f.created_at
          from filtered f
          cross join lateral jsonb_array_elements(f.answers) answer_item
          where (answer_item ->> 'question_id') = q.id::text
            and nullif(trim(answer_item ->> 'reason'), '') is not null
          order by f.created_at desc
          limit 50
        ) recent_opinions
      ), '[]'::jsonb) as opinions
    from public.questions q
    left join filtered f on true
    left join lateral jsonb_array_elements(f.answers) a(answer) 
      on (a.answer ->> 'question_id') = q.id::text
    where q.is_active = true
    group by q.id, q.order_num, q.title
  )
  select jsonb_build_object(
    'total_responses', (select count(*) from filtered),
    'questions', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id', id,
          'order_num', order_num,
          'title', title,
          'a_count', a_count,
          'b_count', b_count,
          'total', total,
          'opinions', opinions
        ) order by order_num
      )
      from question_stats
    ), '[]'::jsonb)
  );
$$;

revoke all on function public.get_public_stats(text, text) from public;
grant execute on function public.get_public_stats(text, text) to anon, authenticated;

